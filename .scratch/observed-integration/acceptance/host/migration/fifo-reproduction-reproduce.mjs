import { mkdtempSync, realpathSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawn, execFileSync } from 'node:child_process';
const worktree = '/Users/hugues_mini/orca/workspaces/jev-ios-bridge/feat-observed-offline-migration';
const head = execFileSync('git', ['rev-parse', 'HEAD'], {cwd:worktree, encoding:'utf8'}).trim();
const fixture = realpathSync(mkdtempSync(join(tmpdir(), 'migration-review-fifo-')));
const leases = join(fixture, 'leases'); mkdirSync(leases, {mode:0o700});
const root = join(fixture, 'admission');
const fifo = join(leases, '11111111-2222-4333-8444-555555555555.lock');
execFileSync('mkfifo', [fifo]);
const code = `import { migrateAdmissionForTesting } from './src/device/admission-migration.ts';
const options = JSON.parse(process.argv[1]);
console.log('entered');
try { console.log(JSON.stringify(migrateAdmissionForTesting({version:1,writersStopped:true,historicalRootsDeclaredOrExcluded:true,additionalJournalRoots:[],additionalLeaseRoots:[],excludedDevices:[]}, options))); }
catch(error) { console.log(JSON.stringify({code:error.code,message:error.message})); process.exitCode=3; }`;
const args = ['--import','tsx','--input-type=module','-e',code,JSON.stringify({root,backend:'fake',defaultRoots:{journal:join(fixture,'absent-journal'),leases}})];
const startedAt = Date.now();
const child = spawn(process.execPath, args, {cwd:worktree, stdio:['ignore','pipe','pipe']});
let stdout = ''; let stderr = ''; let timedOut = false;
child.stdout.on('data', data => { stdout += data; });
child.stderr.on('data', data => { stderr += data; });
const timeoutMs = 2000;
const timer = setTimeout(() => { timedOut = true; child.kill('SIGKILL'); }, timeoutMs);
const exit = await new Promise(resolve => child.once('close', (exitCode, signal) => resolve({exitCode,signal})));
clearTimeout(timer);
console.log(JSON.stringify({label:'newly saved repeat of FIFO reproduction',head,worktree,node:process.version,fixture,fifo,timeoutMs,elapsedMs:Date.now()-startedAt,timedOut,...exit,stdout,stderr,guardRetained:existsSync(join(root,'migration.lock'))},null,2));
rmSync(fixture,{recursive:true,force:true});
console.log('Temporary source and admission fixtures removed.');
